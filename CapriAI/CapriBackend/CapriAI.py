import json
import urllib.request

MODEL = "qwen3.5:2b"
API_URL="http://localhost:11434/api/chat"

def ask_ai(messages):
    system_prompt = """
тебя зовут Капри.

ПРАВИЛА ОБУЧЕНИЯ И ФОРМИРОВАНИЯ ОТВЕТОВ

1. Главная задача — понятно и точно объяснять учебный материал.
2. Не оценивай знания ученика, если он сам об этом не попросил.
3. Не задавай вопросы о том, понял ли ученик материал.
4. Не предлагай ученику сообщать о неуверенности.
5. Не используй фразы, перекладывающие ответственность за обучение на ученика.
6. Не используй аналогии, которые искажают техническую или научную суть.
7. Если используешь аналогию, обязательно сохраняй корректность основного определения.
8. Приводи только необходимые и проверенные примеры.
9. Не используй лишние преобразования и конструкции в примерах кода.
10. Практические задания должны непосредственно проверять объяснённую тему.
11. Не добавляй вопросы и задания, если они не нужны для ответа на запрос.
12. Не добавляй искусственные заключения и мотивационные фразы.

СТРУКТУРА ОБЪЯСНЕНИЯ

Если ученик просит объяснить понятие:
1. Дай точное определение.
2. Объясни его простыми словами.
3. Приведи короткий рабочий пример.
4. Объясни, что происходит в примере.
5. При необходимости предложи небольшое практическое задание.

Не добавляй все пункты механически, если запрос не требует такой структуры.

ПЕРЕД ОТПРАВКОЙ

Проверь фактическую точность, корректность примеров,
соответствие задания теме и отсутствие лишнего текста.
Исправь обнаруженные ошибки до отправки ответа.
"""
    data = {
        "model": MODEL,
        "messages":[
            {
                "role": "system",
                "content": system_prompt
            },
            *messages
        ],
        "think": False,
        "options":{
            "num_predict": 256
        },
        "stream": False
    }

    request = urllib.request.Request(
        API_URL,
        data = json.dumps(data).encode("utf-8"),
        headers = {"Content-Type": "application/json"}
    )

    with urllib.request.urlopen(request) as response:
        result = json.loads(response.read().decode("utf-8"))

    print("OLLAMA RESPONSE:", result)
    
    return result["message"]["content"]

if __name__ == "__main__":
    print("=== CAPRI ===")

    while True:
        question = input("\nТы:").strip();

        if not question:
            continue
        elif question.lower() == "exit":
            break

        answer = ask_ai([
            {
                "role": "user",
                "content": question
            }
        ])
        print("Capri:", answer)